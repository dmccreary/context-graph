# --- Read concept labels from concept-list.md ---
labels = {}
with open("concept-list.md") as f:
    for line in f:
        m = re.match(r'^(\d+)\. (.+)$', line.strip())
        if m:
            labels[int(m.group(1))] = m.group(2)

# --- Validate ---
missing = [i for i in range(1, 497) if i not in labels]
if missing:
    print(f"WARNING: missing labels for IDs: {missing}")
no_dep = [i for i in range(1, 497) if i not in deps]
if no_dep:
    print(f"WARNING: missing dep entries for IDs: {no_dep}")

# --- Write CSV ---
with open("learning-graph.csv", "w", newline="") as f:
    writer = csv.writer(f)
    writer.writerow(["ConceptID", "ConceptLabel", "Dependencies"])
    for i in range(1, 497):
        writer.writerow([i, labels.get(i, f"MISSING_{i}"), deps.get(i, "")])

print(f"Written learning-graph.csv with {len(labels)} concepts")
